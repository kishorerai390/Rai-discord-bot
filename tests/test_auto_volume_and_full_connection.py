import asyncio
import pytest
from unittest.mock import MagicMock, AsyncMock
from aiohttp.test_utils import AioHTTPTestCase, unittest_run_loop
from aiohttp import web

from web.server import RaiCommunityOSServer
from web.auth import AuthManager
from database.database import Database
import cogs.basic as basic_cog_module

class TestAutoVolumeAndFullConnection(AioHTTPTestCase):
    async def get_application(self):
        self.db = Database(":memory:")
        await self.db.connect()
        self.mock_bot = MagicMock()
        self.mock_bot.guilds = []
        self.server = RaiCommunityOSServer(bot=self.mock_bot, db=self.db, port=8999)
        app = web.Application()
        self.server.setup_routes(app)
        return app

    async def tearDownAsync(self):
        await self.db.close()
        await super().tearDownAsync()

    @unittest_run_loop
    async def test_01_guest_token_authorization(self):
        """Guest listener tokens (generated by web browser) are authenticated for music controls."""
        auth_header = {"Authorization": "Bearer guest_listener_test123"}
        payload = {
            "guild_id": 1525030316845301781,
            "action": "VOLUME",
            "payload": {"volume": 85},
        }
        resp = await self.client.post("/api/music/control", json=payload, headers=auth_header)
        assert resp.status == 200
        json_data = await resp.json()
        assert json_data["success"] is True

    @unittest_run_loop
    async def test_02_volume_dispatch_updates_volume(self):
        """Volume action returns updated volume and persists."""
        auth_header = {"Authorization": "Bearer guest_listener_test123"}
        payload = {
            "guild_id": 1525030316845301781,
            "action": "VOLUME",
            "payload": {"volume": 95},
        }
        resp = await self.client.post("/api/music/control", json=payload, headers=auth_header)
        assert resp.status == 200
        data = await resp.json()
        assert data["data"]["volume"] == 95

    @unittest_run_loop
    async def test_03_autodj_toggle_dispatch(self):
        """AutoDJ / autoplay toggle action functions properly via web dispatch."""
        auth_header = {"Authorization": "Bearer guest_listener_test123"}
        payload = {
            "guild_id": 1525030316845301781,
            "action": "AUTODJ_TOGGLE",
            "payload": {},
        }
        resp = await self.client.post("/api/music/control", json=payload, headers=auth_header)
        assert resp.status == 200
        data = await resp.json()
        assert data["success"] is True
        assert data["data"]["action"] in ("AUTODJ_TOGGLE", "AUTOPLAY_TOGGLE")

    def test_04_basic_cog_commands_exist(self):
        """Verify autoplay and volume hybrid commands exist in cogs.basic."""
        cog_cls = basic_cog_module.Basic
        cmd_names = [getattr(attr, "name", None) for attr in cog_cls.__dict__.values()]
        assert "autoplay" in cmd_names
        assert "volume" in cmd_names

    @unittest_run_loop
    async def test_05_session_endpoint_includes_volume_and_autodj(self):
        """GET /api/music/session contains valid volume and auto_dj properties."""
        resp = await self.client.get("/api/music/session?guild_id=1525030316845301781")
        assert resp.status == 200
        json_data = await resp.json()
        assert json_data["success"] is True
        assert "volume" in json_data["data"]
        assert "auto_dj" in json_data["data"]

